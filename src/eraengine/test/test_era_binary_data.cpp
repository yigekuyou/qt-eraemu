#include "era_binary_data.h"
#include <QCoreApplication>
#include <QDebug>
#include <QFile>
#include <QDir>
#include <limits>
using namespace EraBinaryData;
int main(int argc, char** argv) {
    QCoreApplication app(argc, argv);
    int failures = 0;
    auto check = [&](bool ok, const char* what) { if (!ok) { ++failures; qCritical() << what; } };
    // Protocol golden, hand-derived from BinaryWriter(Encoding.Unicode), NOT this encoder:
    // global header; code=42; version=7; description="中\n"; int64 scalar X=min; string S="😀".
    const QByteArray golden = QByteArray::fromHex(
        "894552410d0a1a0a1007000000000000012a000000000000000700000000000000"
        "042d4e0a0000025800d2000000000000008010025300043dd800deff");
    Document d;
    check(decode(golden, d), "independent global golden decode");
    check(d.type == FileType::Global && d.uniqueCode == 42 && d.scriptVersion == 7 && d.description == QString::fromUtf8("中\n"), "metadata and UTF16");
    check(d.variables.size() == 2, "two scalar records");
    if (d.variables.size() == 2) {
        check(d.variables[0].integers == QList<qint64>{std::numeric_limits<qint64>::min()}, "int64 minimum");
        check(d.variables[1].strings == QList<QString>{QString::fromUtf8("😀")}, "UTF16 surrogate pair");
    }
    QByteArray encoded;
    check(encode(d, encoded) && encoded == golden + char(0xff), "writer equals independent scalar golden bytes");
    // Array fixture: rank3 I[3,2,3], empty plane, empty row, zero cell, -1, row/plane ends.
    QByteArray arrays = golden.left(33); arrays.append(char(0)); // empty description
    arrays += QByteArray::fromHex("03024900030000000200000003000000f201f101f001d0ffffe0e1ff"
                                  "1102540004000000f001d80441000a00ffff");
    Document a;
    check(decode(arrays, a), "independent compressed arrays decode");
    if (a.variables.size() == 2) {
        check(a.variables[0].dimensions == QList<int>{3,2,3}, "dimensions retained");
        check(a.variables[0].integers.size() == 18 && a.variables[0].integers.at(10) == -1 && a.variables[0].integers.at(17) == 0, "zero plane row cell and trailing zeros");
        check(a.variables[1].strings == QList<QString>{"", "A\n", "", ""}, "string array marker");
    } else check(false, "array fixture records");
    const QByteArray character = QByteArray::fromHex(
        "894552410d0a1a0a10070000000000000300000000000000000000000000000000"
        "00010000000000000000044e004f0005fd010255000100000001fffeff");
    Document c;
    check(decode(character, c) && c.characters.size() == 1 && c.characters.first().builtins.size() == 1
          && c.characters.first().userDefined.size() == 1, "character count separator EOC EOF");
    for (qsizetype i = 0; i < golden.size(); ++i) {
        Document untouched; untouched.uniqueCode = 99;
        check(!decode(golden.left(i), untouched) && untouched.uniqueCode == 99, "truncation rejected atomically");
    }
    Document untouched; untouched.uniqueCode = 99;
    check(!decode(golden + 'x', untouched) && untouched.uniqueCode == 99, "trailing bytes rejected");
    check(!decode(QByteArray("eraemu-save-v1\nCHARALIST\t"), untouched), "old port text is not binary protocol");
    Variable huge; huge.name = "H"; huge.dimensions = {2147483647,2147483647};
    Document bad; bad.variables.append(huge); QByteArray output("unchanged");
    check(!encode(bad, output) && output == "unchanged", "dimensions rejected atomically");
    // These fixtures were generated by the repository's unmodified C# writer.
    const QString fixtures=QStringLiteral(ERA_TEST_SOURCE_DIR)+QStringLiteral("/fixtures/csharp-save");
    for(const auto& name:QStringList{"normal-plain.bin","global-plain.bin","charvar-plain.bin","normal-gzip.bin","global-gzip.bin","charvar-gzip.bin"}) {
        QFile file(fixtures+"/"+name); check(file.open(QIODevice::ReadOnly),"C# fixture opens");
        Document reference; QString error;
        check(decode(file.readAll(),reference,&error),"real C# writer bytes decode");
        check(reference.uniqueCode==Q_INT64_C(0x0102030405060708) && reference.scriptVersion==1808,"C# fixture metadata");
        const auto variables=reference.type==FileType::Global ? reference.variables : reference.characters.value(0).userDefined;
        for(const auto& v:variables) {
            if(v.name=="INT_00") check(v.integers.value(0)==std::numeric_limits<qint64>::min(),"C# integer minimum");
            if(v.name=="I3") check(v.dimensions==QList<int>({5,4,6}) && v.integers.value((3*4+2)*6)==std::numeric_limits<qint64>::max(),"C# sparse 3D array");
            if(v.name=="S2") check(v.strings.value(1*7+2)==QString::fromUtf8("界😀"),"C# UTF16 array");
        }
        QByteArray output; check(encode(reference,output,nullptr,name.contains("gzip")),"reencode C# fixture plain and gzip");
        Document reread; check(decode(output,reread),"gzip writer output decodes");
        if(name.contains("gzip")) { Document unchanged; unchanged.uniqueCode=99; check(!decode(output.left(output.size()-4),unchanged) && unchanged.uniqueCode==99,"truncated gzip rejected atomically"); }
        if(argc>1) { QFile exported(QString::fromLocal8Bit(argv[1])+"/"+name);check(exported.open(QIODevice::WriteOnly) && exported.write(output)==output.size(),"export for original C# reader"); }
    }
    for(const auto& name:QStringList{"normal-text.sav","global-text.sav"}) {
        QFile file(fixtures+"/"+name);check(file.open(QIODevice::ReadOnly),"real C# text fixture opens");
        Document schema;schema.type=name.startsWith("global") ? FileType::Global : FileType::Normal;
        Document native;check(decodeText(file.readAll(),schema,native),"original C# EraDataWriter text decoded");
        check(native.uniqueCode==42 && native.scriptVersion==1808,"text metadata");
        bool found=false;
        for(const auto& v:native.variables) {
            if(v.name=="DAY")check(v.integers.value(0)==7,"native DAY");
            if(v.name=="TEXT_CUBE")check(v.dimensions==QList<int>({2,2,2}) && v.integers.last()==8,"native 3D planes");
            if(v.name=="TEXT_MATRIX" || v.name=="USER_GLOBAL") { found=true;check(v.dimensions==QList<int>({2,3}),"native matrix dimensions"); }
        }
        check(found,"native user matrix found");
        QByteArray text;check(encodeText(native,text),"native text encoder");
        Document reread;check(decodeText(text,schema,reread),"native text reencoded document loads");
    }
    qInfo() << failures << "failures";
    return failures ? 1 : 0;
}
